"""
rz-goresym: Bridge Mandiant GoReSym RTTI / metadata extraction into Rizin.
Automatically bootstraps GoReSym precompiled binaries if missing.
"""

import argparse
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
import zipfile

GORESYM_VERSION = "v3.4.1"
GORESYM_BASE_URL = f"https://github.com/mandiant/GoReSym/releases/download/{GORESYM_VERSION}"


def get_default_install_dir() -> str:
    """Returns ~/.local/share/rizin/rz-goresym or OS equivalent."""
    home = os.path.expanduser("~")
    if platform.system().lower() == "windows":
        local_app_data = os.environ.get("LOCALAPPDATA", os.path.join(home, "AppData", "Local"))
        return os.path.join(local_app_data, "rizin", "rz-goresym")
    return os.path.join(home, ".local", "share", "rizin", "rz-goresym")


def find_or_download_goresym(auto_download: bool = True) -> str:
    """Finds GoReSym binary in PATH, user dirs, or downloads it."""
    # 1. Check PATH
    for name in ["GoReSym", "goresym", "GoReSym.exe"]:
        path = shutil.which(name)
        if path and os.path.isfile(path) and os.access(path, os.X_OK):
            return path

    install_dir = get_default_install_dir()
    bin_name = "GoReSym.exe" if platform.system().lower() == "windows" else "GoReSym"
    target_path = os.path.join(install_dir, bin_name)

    # 2. Check local install directory
    if os.path.isfile(target_path) and os.access(target_path, os.X_OK):
        return target_path

    # 3. Check ~/go/bin
    home_go_bin = os.path.expanduser(f"~/go/bin/{bin_name}")
    if os.path.isfile(home_go_bin) and os.access(home_go_bin, os.X_OK):
        return home_go_bin

    if not auto_download:
        raise FileNotFoundError(
            "GoReSym binary not found. Install it in PATH, or run with --download."
        )

    # 4. Bootstrap download from GitHub release
    sys_os = platform.system().lower()
    os_map = {"linux": "linux", "darwin": "mac", "windows": "windows"}
    if sys_os not in os_map:
        raise RuntimeError(f"Unsupported operating system for precompiled binary: {sys_os}")

    asset_name = f"GoReSym-{os_map[sys_os]}.zip"
    download_url = f"{GORESYM_BASE_URL}/{asset_name}"

    sys.stderr.write(f"[*] GoReSym not found. Downloading official {GORESYM_VERSION} ({asset_name})...\n")
    os.makedirs(install_dir, exist_ok=True)

    with tempfile.NamedTemporaryFile(suffix=".zip", delete=False) as tmp_file:
        tmp_path = tmp_file.name

    try:
        urllib.request.urlretrieve(download_url, tmp_path)
        with zipfile.ZipFile(tmp_path, "r") as zf:
            zf.extractall(install_dir)
    finally:
        if os.path.exists(tmp_path):
            os.unlink(tmp_path)

    if os.path.isfile(target_path):
        os.chmod(target_path, 0o755)
        sys.stderr.write(f"[+] Installed GoReSym to {target_path}\n")
        return target_path

    raise RuntimeError(f"Failed to bootstrap GoReSym to {target_path}")


def sanitize_ident(name: str) -> str:
    """Sanitize Go package/type names into clean identifiers."""
    name = name.replace(" ", "_")
    name = re.sub(r"[^\w\.\*\[\]]", "_", name)
    return name


def map_go_type_to_c(go_type: str, pointer_size: int = 8) -> str:
    """Converts Go type string to valid C/Rizin type representation."""
    if not go_type:
        return "void"
    go_type = go_type.strip()
    if go_type == "string":
        return "string"
    if go_type in ("int", "uintptr"):
        return "int64_t" if pointer_size == 8 else "int32_t"
    if go_type in ("uint", "uintptr"):
        return "uint64_t" if pointer_size == 8 else "uint32_t"
    if go_type == "bool":
        return "bool"
    if go_type.startswith("[]"):
        return "slice"
    if go_type.startswith("*"):
        base = map_go_type_to_c(go_type[1:], pointer_size)
        return f"{base}*"
    if go_type in ("int8", "uint8", "byte"):
        return "uint8_t"
    if go_type in ("int16", "uint16"):
        return "uint16_t"
    if go_type in ("int32", "uint32", "rune"):
        return "uint32_t"
    if go_type in ("int64", "uint64"):
        return "uint64_t"
    return "void*"


def generate_rizin_commands(meta: dict) -> list:
    """Translates GoReSym JSON metadata into Rizin commands."""
    cmds = []
    cmds.append("# Generated by rz-goresym")

    tab_meta = meta.get("TabMeta") or {}
    ptr_size = tab_meta.get("PointerSize", 8)
    go_ver_str = meta.get("Version") or meta.get("BuildInfo", {}).get("GoVersion", "")

    # Determine default calling convention
    # Go 1.17+ on x86_64/arm64 uses register-based ABI
    is_reg_abi = True
    if go_ver_str:
        m = re.search(r"1\.(\d+)", go_ver_str)
        if m and int(m.group(1)) < 17:
            is_reg_abi = False

    cc_name = "golang" if is_reg_abi else "golang_abi0"

    # 1. Recover functions
    user_funcs = meta.get("UserFunctions") or []
    std_funcs = meta.get("StdFunctions") or []
    all_funcs = user_funcs + std_funcs

    for fn in all_funcs:
        start = fn.get("Start")
        if start is None:
            continue
        start_va = hex(start)
        full_name = fn.get("FullName", "")
        if not full_name:
            continue

        clean_name = sanitize_ident(full_name)
        flag_name = f"sym.go.{clean_name}"

        # Flag and define function
        cmds.append(f"f+ {flag_name} 1 {start_va}")
        cmds.append(f"s {start_va}")
        cmds.append(f"af {start_va} {flag_name}")
        cmds.append(f"afc {cc_name}")

        # Add source file comment if available
        src_file = fn.get("File")
        src_line = fn.get("Line")
        if src_file:
            cmt = f"Source: {src_file}:{src_line}" if src_line else f"Source: {src_file}"
            cmds.append(f"CC \"{cmt}\"")

    # 2. Recover user-defined and RTTI types
    types = meta.get("Types") or []
    for t in types:
        kind = t.get("Kind", "")
        type_name = t.get("Str", "")
        if not type_name or kind != "struct":
            continue

        fields = t.get("Fields") or []
        if not fields:
            continue

        clean_struct = sanitize_ident(type_name).replace(".", "_")
        c_fields = []
        for fld in fields:
            fld_name = fld.get("Name", "") or f"field_{fld.get('Offset', 0)}"
            fld_type_raw = fld.get("Type", {}).get("Str", "void*")
            fld_type_c = map_go_type_to_c(fld_type_raw, ptr_size)
            c_fields.append(f"{fld_type_c} {fld_name};")

        struct_body = " ".join(c_fields)
        cmds.append(f'td "struct {clean_struct} {{ {struct_body} }}"')

    return cmds


def main():
    parser = argparse.ArgumentParser(
        description="rz-goresym: Mandiant GoReSym bridge for Rizin."
    )
    parser.add_argument("binary", nargs="?", help="Path to Go binary to analyze")
    parser.add_argument("-o", "--output", help="Write commands to script file instead of stdout")
    parser.add_argument("-i", "--interactive", action="store_true", help="Launch interactive rizin with applied symbols")
    parser.add_argument("--download", action="store_true", help="Ensure GoReSym is downloaded without running analysis")
    parser.add_argument("--goresym-path", help="Explicit path to GoReSym executable")
    parser.add_argument("--rizin-bin", default="rizin", help="Path to rizin executable (default: rizin)")

    args = parser.parse_args()

    if args.download:
        path = find_or_download_goresym(auto_download=True)
        print(f"GoReSym ready at: {path}")
        return 0

    if not args.binary:
        parser.print_help()
        return 1

    if not os.path.isfile(args.binary):
        sys.stderr.write(f"Error: binary '{args.binary}' does not exist.\n")
        return 1

    goresym_bin = args.goresym_path or find_or_download_goresym(auto_download=True)

    cmd = [goresym_bin, "-t", "-p", "-d", args.binary]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0 and not proc.stdout:
        sys.stderr.write(f"GoReSym execution failed: {proc.stderr}\n")
        return 1

    try:
        meta = json.loads(proc.stdout)
    except json.JSONDecodeError as e:
        sys.stderr.write(f"Failed to parse GoReSym JSON output: {e}\n")
        return 1

    cmds = generate_rizin_commands(meta)

    if args.interactive:
        with tempfile.NamedTemporaryFile("w", suffix=".rz", delete=False) as tmp_script:
            tmp_script.write("\n".join(cmds) + "\n")
            script_path = tmp_script.name
        try:
            subprocess.run([args.rizin_bin, "-i", script_path, args.binary])
        finally:
            if os.path.exists(script_path):
                os.unlink(script_path)
    elif args.output:
        with open(args.output, "w") as f:
            f.write("\n".join(cmds) + "\n")
        sys.stderr.write(f"[+] Wrote {len(cmds)} commands to {args.output}\n")
    else:
        try:
            for c in cmds:
                print(c)
        except BrokenPipeError:
            pass

    return 0


if __name__ == "__main__":
    sys.exit(main())
